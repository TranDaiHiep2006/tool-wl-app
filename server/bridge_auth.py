"""Bridge authentication — per-install secret token for the WS bridge.

P3 §3B Option 1: keep the WebSocket bridge but require the connecting
extension to present a per-install secret token. The token:

    * is generated the FIRST TIME we need it (high-entropy random);
    * is stored at `config/bridge_token` (gitignored) and exposed to the
      extension via `extension/token.js` (gitignored) so the extension
      can include it in its `hello` handshake;
    * can be rotated via `scripts/rotate_bridge_token.py`;
    * is checked by `server/browser_dom.DOMBridge` before any request is
      served — a client without the correct token is closed (code 1008,
      "policy violation") and never sees our data.

Threat model
------------
The bridge binds strictly to 127.0.0.1:57532 (already enforced in P2).
This token closes the residual risk that a stray extension or script on
the same machine connects without authorization. The token itself never
leaves loopback.

Limitations
-----------
The token does NOT protect against an attacker who can read files on the
user's disk — they can read the token and impersonate the extension. That
matches the P3 threat model: this is an extra hurdle against accidental
or casual misuse, not a defense against a local root user.
"""

from __future__ import annotations

import logging
import os
import secrets
from pathlib import Path
from typing import Optional

_log = logging.getLogger("tool_wl_app.bridge_auth")


# --------------------- paths -------------------------------------------------

ROOT_DIR: Path = Path(__file__).resolve().parent.parent
CONFIG_DIR: Path = ROOT_DIR / "config"
EXT_DIR: Path = ROOT_DIR / "extension"

TOKEN_FILE: Path = CONFIG_DIR / "bridge_token"
TOKEN_JS_FILE: Path = EXT_DIR / "token.js"
TOKEN_JS_TEMPLATE: str = (
    "// AUTO-GENERATED by server/bridge_auth.py — DO NOT EDIT BY HAND.\n"
    "// Token used to authenticate the extension to the loopback WS bridge.\n"
    "// gitignored; safe to commit only the placeholder structure.\n"
    "export const BRIDGE_TOKEN = {token_json};\n"
)


def _ensure_config_dir() -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)


def _ensure_ext_dir() -> None:
    EXT_DIR.mkdir(parents=True, exist_ok=True)


# --------------------- token lifecycle --------------------------------------


def _generate_token() -> str:
    """Generate a new high-entropy URL-safe token."""
    # 32 bytes → 43-char URL-safe string.
    return secrets.token_urlsafe(32)


def _read_token_file() -> Optional[str]:
    try:
        lines = TOKEN_FILE.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return None
    for line in lines:
        line = line.strip()
        if not line:
            continue
        # Skip comment lines (the token file starts with a comment header).
        if line.startswith("#"):
            continue
        return line
    return None


def _write_token_files(token: str) -> None:
    """Persist the token to BOTH the config file and the extension module."""
    _ensure_config_dir()
    TOKEN_FILE.write_text(
        "# tool-wl-app bridge token. DO NOT COMMIT.\n"
        + token
        + "\n",
        encoding="utf-8",
    )
    _ensure_ext_dir()
    TOKEN_JS_FILE.write_text(
        TOKEN_JS_TEMPLATE.format(token_json=_js_quote(token)),
        encoding="utf-8",
    )
    try:
        TOKEN_JS_FILE.chmod(0o644)
    except Exception:
        pass


def _js_quote(s: str) -> str:
    """Quote a string as a JS double-quoted literal."""
    escaped = (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def get_or_create_token() -> str:
    """Return the current bridge token, generating one if needed.

    The token is persisted atomically to disk on first use. Subsequent
    calls return the same token. Use `rotate_token()` to change it.
    """
    existing = _read_token_file()
    if existing:
        # Make sure the JS sibling file exists too (it might have been
        # deleted manually). Idempotent — safe to overwrite with the same.
        if not TOKEN_JS_FILE.exists() or _read_js_token() != existing:
            try:
                _ensure_ext_dir()
                TOKEN_JS_FILE.write_text(
                    TOKEN_JS_TEMPLATE.format(token_json=_js_quote(existing)),
                    encoding="utf-8",
                )
            except OSError as exc:
                _log.warning("could not refresh token.js: %r", exc)
        return existing
    token = _generate_token()
    try:
        _write_token_files(token)
    except OSError as exc:
        _log.error("could not persist bridge token: %r", exc)
        # Still return the in-memory token so the running session works;
        # a restart won't remember it but the user will see the warning.
    return token


def _read_js_token() -> Optional[str]:
    try:
        text = TOKEN_JS_FILE.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    # Look for `export const BRIDGE_TOKEN = "...";`
    import re
    m = re.search(r'BRIDGE_TOKEN\s*=\s*"((?:[^"\\]|\\.)*)"', text)
    if not m:
        return None
    raw = m.group(1)
    try:
        # Decode the same way we encode.
        return (
            raw.replace("\\n", "\n")
            .replace("\\r", "\r")
            .replace("\\t", "\t")
            .replace('\\"', '"')
            .replace("\\\\", "\\")
        )
    except Exception:
        return None


def rotate_token() -> str:
    """Force-generate a new token and overwrite all token files."""
    token = _generate_token()
    try:
        _write_token_files(token)
    except OSError as exc:
        _log.error("could not persist rotated bridge token: %r", exc)
        raise
    return token


def current_token() -> Optional[str]:
    """Read the persisted token without generating one."""
    return _read_token_file()